// The logo pack (marketing/logo-pack/): the AntaraX logos in the forms printers, partners and slide decks ask for.
// For each logo: the SVG (master), a vector PDF on a page the size of the art (100 mm wide, scale it freely), and a
// transparent PNG 2000 px wide. Sources are assets/antarax/; never edit the pack by hand, run this again.
//   NODE_PATH=$(npm root -g) node tools/build-logo-pack.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');

const KIT = new URL('../', import.meta.url).pathname;
const OUT = KIT + 'marketing/logo-pack/';
// [file in assets/antarax, pack name, what it is] (the one-colour sparkle is written navy and white)
const LOGOS = [
  ['antarax-mark.svg', 'antarax-mark-blue', 'the A, blue, for light grounds'],
  ['antarax-mark-white.svg', 'antarax-mark-white', 'the A, white, for blue and dark grounds'],
  ['antarax-wordmark.svg', 'antarax-wordmark-navy', 'the wordmark, navy with the blue A, for light grounds'],
  ['antarax-wordmark-white.svg', 'antarax-wordmark-white', 'the wordmark, white, for navy, blue and dark grounds'],
  ['antarax-a-kain.svg', 'antarax-a-kain', 'the kain A, large uses only'],
  ['antarax-a-kain-open.svg', 'antarax-a-kain-open', 'the open kain A, its eye free for a QR code or art'],
  ['sparkle.svg', 'antarax-sparkle', 'the AI sparkle, in colour'],
  ['sparkle-mono.svg', 'antarax-sparkle-navy', 'the sparkle in one colour, navy', '#0B1B4F'],
  ['sparkle-mono.svg', 'antarax-sparkle-white', 'the sparkle in one colour, white', '#FFFFFF'],
];
const MM = 96 / 25.4, WIDTH_MM = 100, PNG_W = 2000;

// Chrome rasterises anything under a <mask> when it prints, so the A's eye (a white rect with a black circle) becomes
// the same shape as a clip path, rect minus circle, even-odd. Same drawing, and the PDF stays vector.
const num = (tag, a, d = 0) => +(tag.match(new RegExp(`\\s${a}="([-\\d.]+)"`)) || [, d])[1];
const vectorEyes = (svg) => {
  const ids = [];
  svg = svg.replace(/<mask id="([^"]+)"[^>]*>\s*(<rect[^>]*\/>)\s*(<circle[^>]*\/>)\s*<\/mask>/g, (m, id, rect, circle) => {
    if (!/fill="#(fff|ffffff)"/i.test(rect) || !/fill="#(000|000000)"/i.test(circle)) throw new Error(`mask ${id} is not a plain eye`);
    const [x, y, w, h] = ['x', 'y', 'width', 'height'].map((a) => num(rect, a));
    const [cx, cy, r] = ['cx', 'cy', 'r'].map((a) => num(circle, a));
    ids.push(id);
    return `<clipPath id="${id}"><path clip-rule="evenodd" d="M${x},${y}h${w}v${h}h${-w}Z M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0Z"/></clipPath>`;
  });
  for (const id of ids) svg = svg.replaceAll(`mask="url(#${id})"`, `clip-path="url(#${id})"`);
  if (/<mask/.test(svg)) throw new Error('a mask is left that is not an eye: the PDF would be rasterised');
  return svg;
};

fs.rmSync(OUT, { recursive: true, force: true });
for (const d of ['svg', 'pdf', 'png']) fs.mkdirSync(OUT + d, { recursive: true });
const browser = await chromium.launch();
const rows = [];
for (const [file, name, what, colour] of LOGOS) {
  let svg = fs.readFileSync(KIT + 'assets/antarax/' + file, 'utf8');
  if (colour) svg = svg.replaceAll('currentColor', colour);
  svg = vectorEyes(svg.replace(/<style>[\s\S]*?<\/style>/, '')); // the kain A's sparkle wobble is for screens only
  fs.writeFileSync(`${OUT}svg/${name}.svg`, svg);
  const [, , vw, vh] = svg.match(/viewBox="([^"]+)"/)[1].trim().split(/[\s,]+/).map(Number);
  const w = WIDTH_MM * MM, h = w * vh / vw;
  const html = (W, H) => `<!doctype html><html><head><style>@page{size:${W}px ${H}px;margin:0}html,body{margin:0;background:transparent}img{display:block;width:${W}px;height:${H}px}</style></head><body><img src="file://${OUT}svg/${name}.svg"></body></html>`;
  const tmp = `${OUT}.tmp.html`;
  let page = await browser.newPage({ viewport: { width: Math.ceil(w), height: Math.ceil(h) } });
  fs.writeFileSync(tmp, html(w, h)); await page.goto('file://' + tmp); await page.waitForTimeout(150);
  await page.pdf({ path: `${OUT}pdf/${name}.pdf`, width: `${w}px`, height: `${h}px`, printBackground: false, pageRanges: '1' });
  await page.close();
  const ph = Math.round(PNG_W * vh / vw);
  page = await browser.newPage({ viewport: { width: PNG_W, height: ph } });
  fs.writeFileSync(tmp, html(PNG_W, ph)); await page.goto('file://' + tmp); await page.waitForTimeout(150);
  await page.screenshot({ path: `${OUT}png/${name}.png`, omitBackground: true });
  await page.close(); fs.unlinkSync(tmp);
  rows.push(`| \`${name}\` | ${what} | ${WIDTH_MM} × ${(h / MM).toFixed(0)} mm | ${PNG_W} × ${ph} px |`);
  console.log(name);
}
await browser.close();
fs.writeFileSync(OUT + 'CONTENTS.md', `# Logo pack contents\n\nGenerated by \`tools/build-logo-pack.mjs\` from \`assets/antarax/\`. Each logo comes as \`svg/\`, \`pdf/\` (vector, scale freely) and \`png/\` (transparent).\n\n| Name | What it is | PDF page | PNG |\n|---|---|---|---|\n${rows.join('\n')}\n`);
